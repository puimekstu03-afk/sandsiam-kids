import json, math, sys
src, out = sys.argv[1], sys.argv[2]
NORTH = {'Chiang Mai','Chiang Rai','Lampang','Lamphun','Mae Hong Son','Nan','Phayao','Phrae','Uttaradit'}
ISAN = {'Amnat Charoen','Bueng Kan','Buri Ram','Chaiyaphum','Kalasin','Khon Kaen','Loei','Maha Sarakham','Mukdahan','Nakhon Phanom','Nakhon Ratchasima','Nong Bua Lam Phu','Nong Khai','Roi Et','Sakon Nakhon','Si Sa Ket','Surin','Ubon Ratchathani','Udon Thani','Yasothon'}
EAST = {'Chanthaburi','Chachoengsao','Chon Buri','Prachin Buri','Rayong','Sa Kaeo','Trat'}
SOUTH = {'Chumphon','Krabi','Nakhon Si Thammarat','Narathiwat','Pattani','Phangnga','Phatthalung','Phuket','Ranong','Satun','Songkhla','Surat Thani','Trang','Yala'}
WEST = {'Tak','Kanchanaburi','Ratchaburi','Phetchaburi','Prachuap Khiri Khan'}
def region(n):
    if n in NORTH: return 0
    if n in ISAN: return 2
    if n in EAST: return 3
    if n in SOUTH: return 4
    return 1  # central (West merged in)
d = json.load(open(src))
feats = d['features']
lons = [c[0] for f in feats for poly in (f['geometry']['coordinates'] if f['geometry']['type']=='MultiPolygon' else [f['geometry']['coordinates']]) for ring in poly for c in ring]
lats = [c[1] for f in feats for poly in (f['geometry']['coordinates'] if f['geometry']['type']=='MultiPolygon' else [f['geometry']['coordinates']]) for ring in poly for c in ring]
lon0, lon1, lat0, lat1 = min(lons), max(lons), min(lats), max(lats)
kx = math.cos(math.radians(13))
W = 300
scale = W / ((lon1 - lon0) * kx)
H = (lat1 - lat0) * scale
proj = lambda c: ((c[0] - lon0) * kx * scale, (lat1 - c[1]) * scale)
paths = ['', '', '', '', '']
counts = [0]*5
sums = [[0,0,0] for _ in range(5)]
west_names = []
for f in feats:
    name = f['properties']['ADM1_EN']
    r = region(name); counts[r] += 1
    if name in WEST: west_names.append(f['properties']['ADM1_TH'])
    g = f['geometry']
    polys = g['coordinates'] if g['type']=='MultiPolygon' else [g['coordinates']]
    for poly in polys:
        for ring in poly[:1]:  # outer ring only
            pts = [proj(c) for c in ring]
            # drop near-duplicate points
            kept = [pts[0]]
            for p in pts[1:]:
                if abs(p[0]-kept[-1][0]) + abs(p[1]-kept[-1][1]) > 0.6: kept.append(p)
            if len(kept) < 3: continue
            paths[r] += 'M' + 'L'.join(f'{x:.1f},{y:.1f}' for x,y in kept) + 'Z'
            for x,y in kept: sums[r][0]+=x; sums[r][1]+=y; sums[r][2]+=1
labels = [[round(s[0]/s[2],1), round(s[1]/s[2],1)] for s in sums]
data = {'viewBox': f'0 0 {W} {H:.0f}', 'regions': paths, 'labels': labels}
js = ("'use strict';\n\n/**\n * SANDSIAM · Map of Thailand for choosing a region (generated by tools/build-map.py).\n"
      " * Source: Thailand province boundaries (admin level 1) from piyayut-ch/mapthai (MIT),\n"
      " * based on Royal Thai Survey Department data via UNOCHA, simplified. Provinces are\n"
      " * grouped into the game's five regions; the West is merged into Central.\n */\n"
      "const THAI_MAP = " + json.dumps(data, ensure_ascii=False) + ";\n")
open(out, 'w').write(js)
print('provinces per region', counts, 'bytes', len(js), 'viewBox', data['viewBox'], 'west', west_names, 'labels', labels)
